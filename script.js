/* =====================================================
   SHUFFLE FUNCTION
===================================================== */

function shuffle(array) {

    const newArray = [...array];

    for (
        let i = newArray.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(Math.random() * (i + 1));

        [
            newArray[i],
            newArray[j]
        ] =
        [
            newArray[j],
            newArray[i]
        ];
    }

    return newArray;
}


/* =====================================================
   START NEW TEST
===================================================== */

function startNewTest() {

    clearInterval(timerInterval);

    score = 0;

    currentQuestion = 0;

    selectedAnswer = null;

    studentAnswers = [];

    quizQuestions =
        shuffle(questionBank[selectedLanguage]);


    /* Show quiz */

    languageScreen.style.display = "none";

    reviewScreen.style.display = "none";

    resultScreen.style.display = "none";

    quizScreen.style.display = "block";


    /* Update language */

    quizLanguage.textContent =
        `${selectedLanguage} Quiz`;

    attemptNumber.textContent =
        currentAttempt;


    /* Reset score */

    headerScore.textContent = "0";

    currentScore.textContent = "0";


    totalQuestions.textContent =
        quizQuestions.length;


    loadQuestion();
}


/* =====================================================
   LOAD QUESTION
===================================================== */

function loadQuestion() {

    clearInterval(timerInterval);

    selectedAnswer = null;

    nextBtn.disabled = true;


    const current =
        quizQuestions[currentQuestion];


    /* Question number */

    questionNumber.textContent =
        currentQuestion + 1;


    /* Question text */

    question.textContent =
        current.question;


    /* Progress */

    const progress =
        ((currentQuestion + 1) /
        quizQuestions.length) * 100;

    progressBar.style.width =
        `${progress}%`;


    /* Clear options */

    optionsContainer.innerHTML = "";


    /* Shuffle options */

    const shuffledOptions =
        shuffle(current.options);


    shuffledOptions.forEach(optionText => {

        const option =
            document.createElement("button");

        option.className = "option";

        option.textContent =
            optionText;


        option.addEventListener(
            "click",
            () => selectOption(option, optionText)
        );


        optionsContainer.appendChild(option);

    });


    /* Last question */

    if (
        currentQuestion ===
        quizQuestions.length - 1
    ) {

        nextBtn.textContent =
            "Finish Test ✓";

    } else {

        nextBtn.textContent =
            "Next Question →";

    }


    startTimer();
}


/* =====================================================
   SELECT OPTION
===================================================== */

function selectOption(optionElement, optionText) {

    /* Remove previous selection */

    document
        .querySelectorAll(".option")
        .forEach(option => {

            option.classList.remove("selected");

        });


    /* Select current option */

    optionElement.classList.add("selected");

    selectedAnswer = optionText;

    nextBtn.disabled = false;
}


/* =====================================================
   TIMER
===================================================== */

function startTimer() {

    clearInterval(timerInterval);

    timeLeft = 30;

    timer.textContent = timeLeft;

    timerProgress.style.width = "100%";


    timerInterval =
        setInterval(() => {

            timeLeft--;

            timer.textContent =
                timeLeft;


            const percentage =
                (timeLeft / 30) * 100;

            timerProgress.style.width =
                `${percentage}%`;


            /* Time finished */

            if (timeLeft <= 0) {

                clearInterval(timerInterval);

                submitAnswer();

            }

        }, 1000);
}


