/* =====================================================
   SUBMIT ANSWER
===================================================== */

function submitAnswer() {

    clearInterval(timerInterval);


    /* Prevent double submission */

    if (
        currentQuestion >=
        quizQuestions.length
    ) {
        return;
    }


    const current =
        quizQuestions[currentQuestion];


    const isCorrect =
        selectedAnswer === current.answer;


    /* Save answer */

    studentAnswers.push({

        question:
            current.question,

        selectedAnswer:
            selectedAnswer,

        correctAnswer:
            current.answer,

        isCorrect:
            isCorrect

    });


    /* Add score */

    if (isCorrect) {

        score++;

    }


    /* Update score */

    currentScore.textContent =
        score;

    headerScore.textContent =
        score;


    /* Next question */

    currentQuestion++;


    if (
        currentQuestion <
        quizQuestions.length
    ) {

        loadQuestion();

    } else {

        finishTest();

    }
}


/* =====================================================
   FINISH TEST
===================================================== */

function finishTest() {

    clearInterval(timerInterval);

    quizScreen.style.display = "none";


    /*
       Attempts 1, 2, 3 and 4
       show review.

       Attempt 5
       shows final result.
    */

    if (currentAttempt < MAX_ATTEMPTS) {

        showReview();

    } else {

        showFinalResult();

    }
}


/* =====================================================
   PERFORMANCE MESSAGE
===================================================== */

function getPerformanceMessage(percentage) {

    if (percentage >= 80) {

        return "Excellent";

    } else if (percentage >= 60) {

        return "Good";

    } else if (percentage >= 40) {

        return "Need to improve";

    } else {

        return "Keep practicing";

    }
}


/* =====================================================
   SHOW REVIEW
===================================================== */

function showReview() {

    reviewScreen.style.display =
        "block";


    reviewAttempt.textContent =
        `Attempt ${currentAttempt} of ${MAX_ATTEMPTS}`;


    reviewScore.textContent =
        `${score}/${quizQuestions.length}`;


    const correct =
        studentAnswers.filter(
            item => item.isCorrect
        ).length;


    const wrong =
        studentAnswers.length - correct;


    correctCount.textContent =
        correct;

    wrongCount.textContent =
        wrong;


    const percentage =
        (score / quizQuestions.length) * 100;


    performanceMessage.textContent =
        getPerformanceMessage(percentage);


    /* Clear review */

    reviewList.innerHTML = "";


    /* Display each question */

    studentAnswers.forEach(
        (item, index) => {

            const reviewItem =
                document.createElement("div");


            reviewItem.className =
                item.isCorrect
                    ? "review-item correct"
                    : "review-item wrong";


            let answerHTML = "";


            if (item.isCorrect) {

                answerHTML = `
                    <p class="review-answer correct-answer">
                        ✓ Your Answer:
                        ${item.selectedAnswer}
                    </p>
                `;

            } else {

                answerHTML = `
                    <p class="review-answer">
                        ✗ Your Answer:
                        ${item.selectedAnswer || "Not answered"}
                    </p>

                    <p class="review-answer correct-answer">
                        ✓ Correct Answer:
                        ${item.correctAnswer}
                    </p>
                `;

            }


            reviewItem.innerHTML = `

                <p class="review-question">
                    ${index + 1}.
                    ${item.question}
                </p>

                ${answerHTML}

            `;


            reviewList.appendChild(
                reviewItem
            );

        }
    );


    /* Button text */

    if (
        currentAttempt ===
        MAX_ATTEMPTS - 1
    ) {

        tryAgainBtn.textContent =
            "Start Final Attempt →";

    } else {

        tryAgainBtn.textContent =
            "Try Another Test ↻";

    }
}


