/* =====================================================
   GO TO LANGUAGE SCREEN
===================================================== */

function goToLanguageScreen() {

    clearInterval(timerInterval);


    resultScreen.style.display =
        "none";

    reviewScreen.style.display =
        "none";

    quizScreen.style.display =
        "none";

    languageScreen.style.display =
        "block";


    /* Reset */

    selectedLanguage = "";

    currentAttempt = 1;

    score = 0;

    currentQuestion = 0;

    selectedAnswer = null;

    studentAnswers = [];

    headerScore.textContent = "0";
}


